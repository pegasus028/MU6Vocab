#!/usr/bin/env python3
"""Record every read-aloud item in Back on Your Feet as an MP3 in the Sonia (British English) voice.

  pip install edge-tts
  python tools/make-audio.py            # records only new or changed texts
  python tools/make-audio.py --prune    # also deletes MP3s whose text no longer exists
  python tools/make-audio.py --force    # re-records everything

Needs Node (to read the data files) and internet access. Files go to audio/tts/<key>.mp3 and the
manifest data/tts.js tells app.js which recordings exist; anything missing falls back to the
browser voice. Run it after editing words, examples or story pages, then commit audio/ and data/.
Voice: Microsoft Sonia (en-GB-SoniaNeural) via the free Edge read-aloud service (edge-tts).
"""
import asyncio, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'audio', 'tts')
MANIFEST = os.path.join(ROOT, 'data', 'tts.js')
VOICE, RATE = 'en-GB-SoniaNeural', '-10%'   # app's browser voice also runs at 0.9 speed

if os.environ.get('TTS_CA_BUNDLE'):          # only for networks with an intercepting proxy
    import certifi
    certifi.where = lambda: os.environ['TTS_CA_BUNDLE']
import edge_tts


async def record(item, sem, force):
    path = os.path.join(OUT, item['key'] + '.mp3')
    if not force and os.path.exists(path) and os.path.getsize(path) >= max(8000, 150 * len(item['text'])):
        return 'kept'
    async with sem:
        for attempt in range(4):
            try:
                tmp = path + '.part'
                await edge_tts.Communicate(item['text'], VOICE, rate=RATE).save(tmp)
                # the service sometimes returns a cut-off clip; Sonia averages ~450 bytes per character
                if os.path.getsize(tmp) < max(8000, 150 * len(item['text'])):
                    raise RuntimeError('clip too short (%d bytes)' % os.path.getsize(tmp))
                os.replace(tmp, path)
                return 'made'
            except Exception as e:  # network hiccup or throttling: back off and retry
                if attempt == 3:
                    print('FAILED', item['ref'], e, file=sys.stderr)
                    return 'failed'
                await asyncio.sleep(2 * (attempt + 1))


async def main():
    force, prune = '--force' in sys.argv, '--prune' in sys.argv
    items = json.loads(subprocess.check_output(['node', os.path.join(ROOT, 'tools', 'tts-list.js')], cwd=ROOT))
    os.makedirs(OUT, exist_ok=True)
    sem = asyncio.Semaphore(4)
    results = await asyncio.gather(*(record(i, sem, force) for i in items))
    keys = {i['key'] for i in items}
    if prune:
        for f in os.listdir(OUT):
            if f.endswith('.mp3') and f[:-4] not in keys:
                os.remove(os.path.join(OUT, f))
    have = sorted(i['key'] for i in items if os.path.exists(os.path.join(OUT, i['key'] + '.mp3')))
    with open(MANIFEST, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/make-audio.py: recorded read-aloud clips (Sonia, en-GB). Do not edit. */\n')
        fh.write('window.TTS = { voice: ' + json.dumps(VOICE) + ', dir: "audio/tts/", keys: ' + json.dumps(have) + ' };\n')
    print({k: results.count(k) for k in ('made', 'kept', 'failed')}, '| total', len(items), '| in manifest', len(have))


asyncio.run(main())
